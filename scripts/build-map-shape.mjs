/**
 * Turns the vendored boundary into src/map-shape.ts: two SVG path strings and
 * the projection that placed them, so nothing parses GeoJSON at runtime and
 * the page still makes no request. Re-run after vendor-venezuela-map.mjs:
 *   node scripts/build-map-shape.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync('src/data/venezuela.geo.json', 'utf8'));
const rings = data.features.flatMap((feature) => feature.geometry.coordinates.map((p) => p[0]));

const lons = rings.flat().map((point) => point[0]);
const lats = rings.flat().map((point) => point[1]);
const west = Math.min(...lons);
const east = Math.max(...lons);
const south = Math.min(...lats);
const north = Math.max(...lats);

// Equirectangular with the standard parallel at the middle of the country: at
// this size anything fancier is invisible, and this keeps the shape honest.
const lat0 = (north + south) / 2;
const k = Math.cos((lat0 * Math.PI) / 180);

const WIDTH = 520;
const PAD = 8;
const scale = (WIDTH - PAD * 2) / ((east - west) * k);
const HEIGHT = Math.round((north - south) * scale + PAD * 2);

const round = (value) => Number(value.toFixed(1));
const x = (lon) => round((lon - west) * k * scale + PAD);
const y = (lat) => round((north - lat) * scale + PAD);

function pathFor(id) {
  const feature = data.features.find((candidate) => candidate.properties.id === id);

  return feature.geometry.coordinates
    .map(
      (polygon) =>
        `M${polygon[0].map(([lon, lat]) => `${x(lon)} ${y(lat)}`).join('L')}Z`
    )
    .join('');
}

const file = `/* Generated by scripts/build-map-shape.mjs from src/data/venezuela.geo.json.
   Do not edit by hand: re-vendor the boundary and re-run the script.
   Natural Earth v5, public domain, 10 m admin-0, simplified to 0.02 deg. */

export const MAP_VIEWBOX = { width: ${WIDTH}, height: ${HEIGHT} };

/** Venezuela: the mainland and the islands large enough to see. */
export const MAP_MAINLAND = ${JSON.stringify(pathFor('mainland'))};

/** The Zona en Reclamación, carried separately so it can be hatched. */
export const MAP_CLAIM = ${JSON.stringify(pathFor('claim'))};

/** The same projection the paths were drawn with, for placing the nodes. */
export function project(lon: number, lat: number): { x: number; y: number } {
  return {
    x: Number(((lon - ${west}) * ${k.toFixed(8)} * ${scale.toFixed(6)} + ${PAD}).toFixed(1)),
    y: Number(((${north} - lat) * ${scale.toFixed(6)} + ${PAD}).toFixed(1))
  };
}
`;

writeFileSync('src/map-shape.ts', file);
console.log(`viewBox ${WIDTH}x${HEIGHT}; mainland ${pathFor('mainland').length} chars, claim ${pathFor('claim').length} chars`);
